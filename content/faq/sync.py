"""Generate bundled FAQ copies. Run with --check in CI; no runtime dependency."""

import argparse
import json
from pathlib import Path
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).with_name("catalog.json")
LOCALES = {"ru": "values-ru", "en": "values", "de": "values-de", "fr": "values-fr", "es": "values-es", "zh": "values-zh"}


def outputs(catalog):
    ids = [item["id"] for item in catalog["ru"]]
    assert len(ids) == len(set(ids))
    assert set(catalog) == set(LOCALES)
    for entries in catalog.values():
        assert [item["id"] for item in entries] == ids
        for item, reference in zip(entries, catalog["ru"], strict=True):
            assert item["q"] and item["a"]
            assert item["links"] == reference["links"]
            assert len(re.findall(r"\[[^\]]+\]", item["a"])) == len(item["links"])
            assert set(item["links"]) <= {"support", "payments"}
    bundled = json.dumps(catalog, ensure_ascii=False, indent=2) + "\n"
    bundled = re.sub(r'"links": \[[^\]]*\]', lambda match: '"links": ' + json.dumps(json.loads(match[0][9:]), ensure_ascii=False), bundled)
    for app in ("windows", "chrome-extension"):
        yield ROOT / f"apps/{app}/src/faq.json", bundled
    for locale, folder in LOCALES.items():
        entries = catalog[locale]
        path = ROOT / f"sites/public-website/src/locales/{locale}.json"
        source = path.read_text(encoding="utf-8")
        start = source.index('[', source.index('"questions":', source.index('"help":')))
        _, length = json.JSONDecoder().raw_decode(source[start:])
        rendered = json.dumps(entries, ensure_ascii=False, indent=2).replace("\n", "\n    ")
        yield path, source[:start] + rendered + source[start + length:]
        path = ROOT / f"apps/android/app/src/main/res/{folder}/strings.xml"
        source = re.sub(r'^ *<string name="faq_[^"]+"[^\n]*\n', "", path.read_text(encoding="utf-8"), flags=re.M)
        strings = []
        for item in entries:
            for suffix in ("q", "a"):
                value = escape(item[suffix]).replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
                strings.append(f'    <string name="faq_{item["id"]}_{suffix}">{value}</string>')
        yield path, source.replace("</resources>", "\n".join(strings) + "\n</resources>")
        apple_locale = "zh-Hans" if locale == "zh" else locale
        path = ROOT / f"apps/apple/Resources/{apple_locale}.lproj/Localizable.strings"
        lines = [line for line in path.read_text(encoding="utf-8").splitlines()[1:] if not line.startswith('"faq_')]
        for item in entries:
            for suffix in ("q", "a"):
                lines.append(f'"faq_{item["id"]}_{suffix}" = {json.dumps(item[suffix], ensure_ascii=False)};')
        yield path, "// Generated by scripts/sync-resources.py.\n" + "\n".join(sorted(lines)) + "\n"
    kotlin = ['// Generated by content/faq/sync.py.', 'package com.prettylisavpn.android.ui', '', 'import com.prettylisavpn.android.R', '', 'internal data class FaqEntry(val question: Int, val answer: Int, val links: List<String>)', '', 'internal val faqEntries = listOf(']
    swift = ['// Generated by content/faq/sync.py.', 'struct FAQEntry: Identifiable {', '    let id: String', '    let links: [String]', '}', '', 'let faqEntries: [FAQEntry] = [']
    for item in catalog["ru"]:
        links = ", ".join(json.dumps(link) for link in item["links"])
        key = item["id"]
        kotlin.append(f'    FaqEntry(R.string.faq_{key}_q, R.string.faq_{key}_a, listOf({links})),')
        swift.append(f'    FAQEntry(id: "{key}", links: [{links}]),')
    yield ROOT / "apps/android/app/src/main/java/com/prettylisavpn/android/ui/FaqCatalog.kt", "\n".join(kotlin + [')', ''])
    yield ROOT / "apps/apple/App/FAQCatalog.swift", "\n".join(swift + [']', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads(SOURCE.read_text(encoding="utf-8"))
    stale = []
    for path, expected in outputs(catalog):
        if path.exists() and path.read_text(encoding="utf-8") == expected:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Run python content/faq/sync.py; stale files:\n" + "\n".join(stale))
    print("FAQ copies match the shared catalogue." if args.check else "FAQ copies synchronized.")


if __name__ == "__main__":
    main()
