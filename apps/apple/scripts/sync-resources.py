"""Copy canonical branding and existing six Android locales; add Apple-only copy."""
import json
import re
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
APPLE = ROOT / "apps/apple"
EXTRA = json.loads((APPLE / "Config/AppleStrings.json").read_text(encoding="utf-8"))
LOCALES = {"en": "values", "ru": "values-ru", "de": "values-de", "es": "values-es", "fr": "values-fr", "zh-Hans": "values-zh"}


def escaped(value):
    value = value.replace("\\'", "'").replace("\\n", "\n")
    value = re.sub(r"%(\d+\$)?s", r"%\1@", value)
    return json.dumps(value, ensure_ascii=False)


for index, (locale, folder) in enumerate(LOCALES.items()):
    source = ROOT / f"apps/android/app/src/main/res/{folder}/strings.xml"
    strings = {item.attrib["name"]: "".join(item.itertext()) for item in ET.parse(source).getroot().findall("string")}
    strings.update({key: values[index] for key, values in EXTRA.items()})
    target = APPLE / f"Resources/{locale}.lproj/Localizable.strings"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("// Generated by scripts/sync-resources.py.\n" + "\n".join(f'{escaped(key)} = {escaped(value)};' for key, value in sorted(strings.items())) + "\n", encoding="utf-8")

assets = APPLE / "Resources/Assets.xcassets"
logo = assets / "Logo.imageset"
logo.mkdir(parents=True, exist_ok=True)
shutil.copyfile(ROOT / "docs/assets/prettylisavpn-logo.svg", logo / "logo.svg")
(logo / "Contents.json").write_text(json.dumps({"images": [{"filename": "logo.svg", "idiom": "universal"}], "info": {"version": 1, "author": "xcode"}, "properties": {"preserves-vector-representation": True}}, indent=2) + "\n")
(assets / "Contents.json").write_text('{"info":{"version":1,"author":"xcode"}}\n')

# Exact existing lock artwork; platform icon sizes are derived mechanically.
from PIL import Image

icon = Image.open(ROOT / "apps/windows/src-tauri/icons/icon.png").convert("RGBA")
directory = assets / "AppIcon.appiconset"
directory.mkdir(parents=True, exist_ok=True)
entries = []
for size in (16, 32, 128, 256, 512):
    for scale in (1, 2):
        filename = f"mac-{size}-{scale}.png"
        icon.resize((size * scale, size * scale), Image.Resampling.LANCZOS).save(directory / filename)
        entries.append({"filename": filename, "idiom": "mac", "size": f"{size}x{size}", "scale": f"{scale}x"})
background = Image.new("RGB", (1024, 1024), "#e4e4e4")
large = icon.resize((1024, 1024), Image.Resampling.LANCZOS)
background.paste(large, mask=large.getchannel("A"))
background.save(directory / "ios-1024.png")
entries.append({"filename": "ios-1024.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"})
(directory / "Contents.json").write_text(json.dumps({"images": entries, "info": {"version": 1, "author": "xcode"}}, indent=2) + "\n")
