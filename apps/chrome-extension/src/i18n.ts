export type Label = keyof typeof labels;
export function translate(key: Label, language: Language): string {
  const index = languages.findIndex((item) => item.code === language);
  return labels[key][index]
    .toLocaleLowerCase(language)
    .replaceAll("prettylisavpn", "PrettyLisaVPN");
}
export function languageCode(value: unknown): Language {
  return languages.find((item) => item.code === value)?.code ?? "ru";
}
export const legalKeys = ["terms", "privacy", "refunds", "payments"] as const;
export function publicUrl(
  language: Language,
  document?: (typeof legalKeys)[number],
): string {
  return (
    "https://prettylisavpn.com" +
    (language === "ru" ? "" : "/" + language) +
    (document ? "/legal/" + document + "/" : "/")
  );
}
